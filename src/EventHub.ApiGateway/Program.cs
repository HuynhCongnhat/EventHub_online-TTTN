var builder = WebApplication.CreateBuilder(args);

builder.Logging.ClearProviders();
builder.Logging.AddConsole();
builder.Logging.SetMinimumLevel(LogLevel.Debug);

var destinationAddress = builder.Configuration["ReverseProxy:Clusters:auth-cluster:Destinations:auth-destination:Address"];

Console.WriteLine($"YARP DESTINATION = [{destinationAddress}]");

builder.Services
    .AddReverseProxy()
    .LoadFromConfig(builder.Configuration.GetSection("ReverseProxy"));

var app = builder.Build();

app.Use(async (context, next) =>
{
    Console.WriteLine($"[GATEWAY REQUEST] {context.Request.Method} {context.Request.Path}");

    await next();

    Console.WriteLine($"[GATEWAY REQUEST] {context.Response.StatusCode}");
});

